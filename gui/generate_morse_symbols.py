# ============ Find font ============
font_paths = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationMono-Bold.ttf",
    "/usr/share/fonts/truetype/ubuntu/UbuntuMono-Bold.ttf",
    "/System/Library/Fonts/Menlo.ttc",
    "C:\\Windows\\Fonts\\consola.ttf",
]

font = None
for fp in font_paths:
    if os.path.exists(fp):
        try:
            font = ImageFont.truetype(fp, 72)
            print(f"Using font: {fp}")
            break
        except: continue

if font is None:
    font = ImageFont.load_default()
    print("Using default font")

# ============ Settings ============
WIDTH, HEIGHT = 280, 110
MORSE_COLOR = (0, 0, 0, 255)
BG_COLOR = (0, 0, 0, 0)

count = 0
errors = 0

for char, code in sorted(MORSE.items()):
    try:
        # Create safe filename
        safe_name = str(char)
        replacements = [
            ('/', '_SLASH_'), ('"', '_QUOTE_'), ("'", '_APOS_'),
            ('?', '_QMARK_'), ('!', '_EXCL_'), (':', '_COLON_'),
            (';', '_SEMI_'), ('*', '_STAR_'), ('.', '_DOT_'),
            (',', '_COMMA_'), (' ', '_'),
        ]
        for old, new in replacements:
            safe_name = safe_name.replace(old, new)
        
        # Fallback for purely symbolic names
        if not safe_name or all(c in '._-/' for c in safe_name):
            safe_name = f"CHAR_{ord(char)}"
        
        filename = os.path.join(output_dir, f"{safe_name}.png")
        
        # Create image
        img = Image.new('RGBA', (WIDTH, HEIGHT), BG_COLOR)
        draw = ImageDraw.Draw(img)
        
        # Replace characters for better visual rendering
        display_code = code.replace('-', '▬').replace('.', '●')
        
        # Get text size and center
        bbox = draw.textbbox((0, 0), display_code, font=font)
        tw = bbox[2] - bbox[0]
        th = bbox[3] - bbox[1]
        x = (WIDTH - tw) // 2
        y = (HEIGHT - th) // 2
        
        # Draw
        draw.text((x, y), display_code, fill=MORSE_COLOR, font=font)
        img.save(filename)
        count += 1
        
        if count % 50 == 0:
            print(f"Created {count} symbols...")
            
    except Exception as e:
        errors += 1
        if errors <= 5:
            print(f"Error creating {char}: {e}")

print(f"\n✓ Created {count} Morse code symbol PNGs")
if errors > 0:
    print(f"⚠ {errors} errors (font may not support all Unicode characters)")
print(f"  Location: {os.path.abspath(output_dir)}/")
print("Done!")